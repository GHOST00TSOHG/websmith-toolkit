#!/usr/bin/env node
// Lottie icon fetcher. Only MIT (useAnimations) and CC BY 4.0 (Google Noto animated emoji) sources.
// Usage:
//   node fetch.mjs                      # fetch the default set below
//   node fetch.mjs ua check heart       # add useAnimations icons by export name (see catalog: node fetch.mjs ua-list)
//   node fetch.mjs noto 1f680:rocket    # add Noto animated emoji by codepoint[:name]
//   node fetch.mjs ua-list              # print all useAnimations icon names
// Every file is verified (valid JSON, has v/fr/ip/op/w/h/layers) and INDEX.md is regenerated.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import {execSync} from 'node:child_process';
import {createRequire} from 'node:module';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const LIB = path.join(HERE, 'library');
const UA_VERSION = '3.1.1';
const DEFAULT_UA = ['check','alertCircle','activity','loading','heart','settings','searchToX','arrowRight','lock','bookmark','trash','download','calendar','mail','plusToX','notification','star','infinity','radioButton','toggle','github','userPlus'];
const DEFAULT_NOTO = [
  ['1f680','rocket'],['1f525','fire'],['1f389','party-popper'],['2728','sparkles'],['1f4a1','light-bulb'],
  ['1f914','thinking-face'],['1f60d','heart-eyes'],['1f44d','thumbs-up'],['1f4b8','money-with-wings'],['1f4c8','chart-increasing'],
  ['1f973','partying-face'],['1f62b','tired-face'],['2705','check-mark-button'],['1f3af','bullseye'],['23f0','alarm-clock'],['1f4af','hundred-points'],
];

fs.mkdirSync(path.join(LIB,'useanimations'),{recursive:true});
fs.mkdirSync(path.join(LIB,'noto'),{recursive:true});

function verify(file){
  const j = JSON.parse(fs.readFileSync(file,'utf8'));
  for (const k of ['v','fr','ip','op','w','h','layers']) if (!(k in j)) throw new Error(`${file}: missing ${k}`);
  if (!Array.isArray(j.layers) || j.layers.length===0) throw new Error(`${file}: no layers`);
  return j;
}

function uaPackage(){
  const dir = path.join(os.tmpdir(), `react-useanimations-${UA_VERSION}`);
  if (!fs.existsSync(path.join(dir,'package','package.json'))) {
    fs.mkdirSync(dir,{recursive:true});
    execSync(`curl -sfL https://registry.npmjs.org/react-useanimations/-/react-useanimations-${UA_VERSION}.tgz | tar xz -C ${dir}`);
  }
  return path.join(dir,'package');
}

function fetchUA(names){
  const pkg = uaPackage();
  const req = createRequire(path.join(pkg,'index.js'));
  for (const n of names){
    const mod = req(path.join(pkg,'lib',`${n}.js`));
    const data = (mod.default||mod).animationData;
    if (!data) throw new Error(`useAnimations ${n}: no animationData`);
    const out = path.join(LIB,'useanimations',`${n}.json`);
    fs.writeFileSync(out, JSON.stringify(data));
    verify(out); console.log('ok  useanimations', n);
  }
}

async function fetchNoto(pairs){
  for (const [cp,name] of pairs){
    const url = `https://fonts.gstatic.com/s/e/notoemoji/latest/${cp}/lottie.json`;
    const r = await fetch(url);
    if (!r.ok) { console.error('FAIL noto', cp, r.status); continue; }
    const out = path.join(LIB,'noto',`${name}.json`);
    fs.writeFileSync(out, await r.text());
    try { verify(out); console.log('ok  noto', name, cp); } catch(e){ fs.unlinkSync(out); console.error('FAIL', e.message); }
  }
}

function writeIndex(){
  const rows = [];
  for (const [src,lic,url] of [['useanimations','MIT','https://useanimations.com (react-useanimations@'+UA_VERSION+')'],['noto','CC BY 4.0','https://googlefonts.github.io/noto-emoji-animation/']]){
    for (const f of fs.readdirSync(path.join(LIB,src)).filter(f=>f.endsWith('.json')).sort()){
      const j = verify(path.join(LIB,src,f));
      const cp = src==='noto' ? (DEFAULT_NOTO.find(p=>p[1]===f.replace('.json',''))||[''])[0] : '';
      rows.push(`| ${f.replace('.json','')} | ${src==='noto'?'Google Noto Animated Emoji'+(cp?` (U+${cp.toUpperCase()})`:''):'useAnimations'} | ${lic} | library/${src}/${f} | ${j.w}x${j.h} @${j.fr}fps, ${j.op-j.ip}f |`);
    }
  }
  const md = `# Lottie library index\n\nGenerated by \`node fetch.mjs\`. Only MIT (useAnimations) and CC BY 4.0 (Noto) sources. No Lordicon.\n\n- useAnimations: MIT License, Copyright (c) 2018-2026 useAnimations. Source: https://useanimations.com\n- Noto Animated Emoji: CC BY 4.0, Google. Source: https://googlefonts.github.io/noto-emoji-animation/ (attribution required, see ../CREDITS_TEMPLATE.md)\n\n| name | source | license | path | size / timing |\n|---|---|---|---|---|\n${rows.join('\n')}\n\nTotal: ${rows.length} icons.\n`;
  fs.writeFileSync(path.join(LIB,'INDEX.md'), md);
  console.log(`INDEX.md: ${rows.length} icons`);
}

const [cmd,...args] = process.argv.slice(2);
if (cmd==='ua-list'){ const pkg=uaPackage(); console.log(JSON.parse(fs.readFileSync(path.join(pkg,'catalog.json'))).map(c=>c.export).join(' ')); process.exit(0); }
if (cmd==='ua') fetchUA(args);
else if (cmd==='noto') await fetchNoto(args.map(a=>{const [cp,n]=a.split(':'); return [cp.toLowerCase(), n||cp];}));
else if (!cmd){ fetchUA(DEFAULT_UA); await fetchNoto(DEFAULT_NOTO); }
writeIndex();
